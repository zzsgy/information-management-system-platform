-- 档案模块：从空库建立业务结构，正式表结构只能由 Flyway 版本迁移更新。
-- 密级与保管期限是档案属性，功能授权和数据范围由身份及共享策略独立控制。
CREATE TABLE security_level (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 密级标识
 code VARCHAR(50) NOT NULL UNIQUE, -- 稳定编码
 name VARCHAR(100) NOT NULL, -- 中文名称
 level INTEGER NOT NULL DEFAULT 1, -- 排序级别
 description TEXT -- 管理说明
);
CREATE TABLE retention_period (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 保管期限标识
 code VARCHAR(50) NOT NULL UNIQUE, -- 稳定编码
 name VARCHAR(100) NOT NULL, -- 显示名称
 years INTEGER NOT NULL DEFAULT 0 CHECK(years>=0) -- 零表示永久保管
);
CREATE TABLE numbering_rule (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 编号规则标识
 rule_code VARCHAR(50) NOT NULL UNIQUE, -- 规则编码
 rule_name VARCHAR(100) NOT NULL, -- 中文名称
 pattern VARCHAR(300) NOT NULL DEFAULT '{DEPT}-{CATEGORY}-{YEAR}-{SEQ4}', -- 兼容旧编号模板
 segments TEXT, -- 分段格式 JSON
 scope_type VARCHAR(30) NOT NULL DEFAULT 'dept_category', -- 流水号作用域
 reset_cycle VARCHAR(20) NOT NULL DEFAULT 'YEAR', -- YEAR/MONTH/NONE
 sequence_length INTEGER NOT NULL DEFAULT 4 CHECK(sequence_length BETWEEN 1 AND 18), -- 最小补零长度
 priority INTEGER NOT NULL DEFAULT 0, -- 规则优先级
 enabled INTEGER NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)) -- 是否启用
);
CREATE TABLE numbering_sequence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 序列记录标识
 rule_id BIGINT NOT NULL REFERENCES numbering_rule(id), -- 所属规则
 scope_key VARCHAR(150) NOT NULL, -- 部门及分类组合
 period_key VARCHAR(30) NOT NULL, -- 重置周期
 current_value BIGINT NOT NULL DEFAULT 0, -- 已使用流水值
 UNIQUE(rule_id,scope_key,period_key)
);
CREATE TABLE archive_category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 分类标识
 parent_id BIGINT REFERENCES archive_category(id), -- 上级分类
 category_code VARCHAR(50) NOT NULL UNIQUE, -- 分类编码
 category_name VARCHAR(100) NOT NULL, -- 分类名称
 archive_level INTEGER NOT NULL DEFAULT 1, -- 分类层级
 default_security_level_id BIGINT REFERENCES security_level(id), -- 默认密级
 default_retention_id BIGINT REFERENCES retention_period(id), -- 默认保管期限
 numbering_rule_id BIGINT REFERENCES numbering_rule(id), -- 分类专属编号规则
 sort_order INTEGER NOT NULL DEFAULT 0, -- 显示顺序
 status INTEGER NOT NULL DEFAULT 1 CHECK(status IN (0,1)) -- 是否启用
);
CREATE TABLE archive (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 档案稳定标识，供未来平台关联
 archive_no VARCHAR(100) NOT NULL UNIQUE, -- 不重复档案编号
 archive_name VARCHAR(300) NOT NULL, -- 档案题名
 category_id BIGINT NOT NULL REFERENCES archive_category(id), -- 分类
 dept_id BIGINT NOT NULL REFERENCES ims_department(id), -- 所属部门及默认数据范围
 security_level_id BIGINT REFERENCES security_level(id), -- 访问级别属性
 retention_id BIGINT REFERENCES retention_period(id), -- 保管期限
 archive_year INTEGER, -- 档案年度
 formation_date DATE, -- 形成日期
 filing_date DATE, -- 归档日期
 creator_user_id BIGINT REFERENCES ims_user(id), -- 登记人
 archiver_user_id BIGINT REFERENCES ims_user(id), -- 归档经办人
 keyword VARCHAR(500), -- 检索关键词
 summary TEXT, -- 内容摘要
 physical_location VARCHAR(300), -- 原件位置
 file_type VARCHAR(50), -- 文件类型
 owner_name VARCHAR(100), -- 负责人
 cabinet_no VARCHAR(50), -- 柜号
 column_no VARCHAR(50), -- 列号
 layer_no VARCHAR(50), -- 层号
 storage_type VARCHAR(20), -- 纸质/电子/混合
 copy_count INTEGER NOT NULL DEFAULT 1 CHECK(copy_count>0), -- 保存份数
 archive_date DATE, -- 存档日期
 validity_months INTEGER CHECK(validity_months>0), -- 有效月数
 expiry_date DATE, -- 由存档日期和有效月数计算
 remark TEXT, -- 备注
 volume_no VARCHAR(100), -- 卷盒号
 page_count INTEGER NOT NULL DEFAULT 0 CHECK(page_count>=0), -- 页数
 file_count INTEGER NOT NULL DEFAULT 0, -- 当前附件数量
 status VARCHAR(30) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','archive','borrowed','damaged','destroyed','locked','destroy_pending')), -- 受控生命周期状态
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 登记时间
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 最近修改时间
 deleted_at TIMESTAMP WITH TIME ZONE -- 销毁后软删除时间；不物理删除附件
);
CREATE INDEX ix_archive_department ON archive(dept_id,deleted_at,status);
CREATE INDEX ix_archive_category ON archive(category_id,deleted_at);
CREATE INDEX ix_archive_expiry ON archive(expiry_date,deleted_at);
CREATE TABLE archive_grant (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 授权标识
 archive_id BIGINT NOT NULL REFERENCES archive(id), -- 授权对象
 grantee_type VARCHAR(10) NOT NULL CHECK(grantee_type IN ('user','dept')), -- 人员或部门
 grantee_id BIGINT NOT NULL, -- 被授权主体标识
 permission_code VARCHAR(50) NOT NULL, -- 查询/预览/下载/写入分别授权
 expires_at TIMESTAMP WITH TIME ZONE, -- 可选有效期
 granted_by BIGINT NOT NULL REFERENCES ims_user(id), -- 授权人
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 授权时间
 UNIQUE(archive_id,grantee_type,grantee_id,permission_code)
);
CREATE INDEX ix_archive_grantee ON archive_grant(grantee_type,grantee_id,permission_code,archive_id);
CREATE TABLE archive_file (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 附件版本标识
 archive_id BIGINT NOT NULL REFERENCES archive(id), -- 所属档案
 file_name VARCHAR(255) NOT NULL, -- 原始文件名，同名表示新版本
 file_ext VARCHAR(30), -- 扩展名，不包含点
 mime_type VARCHAR(150), -- 上传内容类型
 storage_key VARCHAR(500) NOT NULL UNIQUE, -- 服务端随机相对路径
 storage_provider VARCHAR(30) NOT NULL DEFAULT 'local', -- 为未来存储适配保留提供方
 file_size BIGINT NOT NULL CHECK(file_size>=0), -- 字节数
 sha256 VARCHAR(64) NOT NULL, -- 完整性校验值
 version_no INTEGER NOT NULL CHECK(version_no>0), -- 同名附件递增版本
 is_current INTEGER NOT NULL DEFAULT 1, -- 是否当前版本
 uploaded_by BIGINT REFERENCES ims_user(id), -- 上传者
 uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 上传时间
 status VARCHAR(20) NOT NULL DEFAULT 'active', -- 文件状态
 UNIQUE(archive_id,file_name,version_no)
);
CREATE TABLE archive_update_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 变更记录标识
 archive_id BIGINT NOT NULL REFERENCES archive(id), -- 档案标识
 operator_id BIGINT REFERENCES ims_user(id), -- 操作人
 operator_name VARCHAR(100), -- 操作人姓名快照
 action VARCHAR(30) NOT NULL, -- 创建/修改/归档/共享动作
 changed_fields TEXT NOT NULL, -- 修改字段列表 JSON
 before_json TEXT, -- 修改前的字段快照
 after_json TEXT, -- 修改后的字段快照
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP -- 变更时间
);
CREATE TABLE operation_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 审计记录标识
 user_id BIGINT REFERENCES ims_user(id), -- 操作用户，可为空表示系统事件
 module VARCHAR(50) NOT NULL, -- 模块
 action VARCHAR(50) NOT NULL, -- 动作
 target_type VARCHAR(80), -- 业务对象类型
 target_id BIGINT, -- 业务对象标识
 detail_json TEXT, -- 不含凭据的业务摘要
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP -- 事件时间
);
CREATE TABLE dict_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 字典项标识
 type_code VARCHAR(80) NOT NULL, -- 字典类型
 item_code VARCHAR(80) NOT NULL, -- 类型内编码
 item_name VARCHAR(150) NOT NULL, -- 中文名称
 sort_order INTEGER NOT NULL DEFAULT 0, -- 显示顺序
 enabled INTEGER NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)), -- 启用状态
 extra_json TEXT, -- 扩展信息
 UNIQUE(type_code,item_code)
);
CREATE TABLE system_parameter (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 参数标识
 param_key VARCHAR(100) NOT NULL UNIQUE, -- 参数键
 param_value TEXT, -- 参数值，禁止保存密码和令牌
 description TEXT -- 中文说明
);
CREATE TABLE notice (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 公告标识
 title VARCHAR(300) NOT NULL, -- 公告标题
 content TEXT, -- 公告正文
 notice_type VARCHAR(30) NOT NULL DEFAULT 'system', -- 公告分类
 publisher_id BIGINT NOT NULL REFERENCES ims_user(id), -- 发布者
 publish_status VARCHAR(20) NOT NULL DEFAULT 'published', -- 发布状态
 publish_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 发布时间
 expire_time TIMESTAMP WITH TIME ZONE, -- 失效时间
 global_visible INTEGER NOT NULL DEFAULT 1, -- 是否全员可见
 deleted_at TIMESTAMP WITH TIME ZONE -- 删除时间
);
CREATE TABLE notice_receiver (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 接收回执标识
 notice_id BIGINT NOT NULL REFERENCES notice(id), -- 公告标识
 user_id BIGINT NOT NULL REFERENCES ims_user(id), -- 指定接收人
 read_at TIMESTAMP WITH TIME ZONE, -- 阅读时间
 UNIQUE(notice_id,user_id)
);
