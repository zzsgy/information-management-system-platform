-- 公共身份模块：平台接入前采用本地账号与会话，业务模块仅依赖统一身份接口。
CREATE TABLE ims_department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 部门稳定标识
    dept_code VARCHAR(50) NOT NULL UNIQUE, -- 唯一部门编码，供档案编号使用
    dept_name VARCHAR(100) NOT NULL, -- 展示名称
    parent_id BIGINT REFERENCES ims_department(id), -- 上级部门，顶层为空
    leader_user_id BIGINT, -- 审批路由使用的负责人，创建用户后补外键
    sort_order INTEGER NOT NULL DEFAULT 0, -- 同层展示顺序
    status INTEGER NOT NULL DEFAULT 1 CHECK (status IN (0, 1)), -- 启用标识
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 创建时间
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 最近修改时间
    deleted_at TIMESTAMP WITH TIME ZONE -- 软删除时间
);

CREATE TABLE ims_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 平台统一用户标识
    username VARCHAR(64) NOT NULL UNIQUE, -- 不可重复的登录账号
    password_hash VARCHAR(255) NOT NULL, -- 加盐PBKDF2密码哈希，不保存明文
    real_name VARCHAR(100) NOT NULL, -- 业务办理人员姓名
    employee_no VARCHAR(50) UNIQUE, -- 可选员工编号
    phone VARCHAR(30), -- 可选联系电话
    email VARCHAR(120), -- 可选联系邮箱
    dept_id BIGINT NOT NULL REFERENCES ims_department(id), -- 默认数据隔离所属部门
    account_status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (account_status IN ('pending','active','rejected','disabled','locked')), -- 非active账号无法使用会话
    last_login_at TIMESTAMP WITH TIME ZONE, -- 最近成功登录时间
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 创建时间
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 最近修改时间
    deleted_at TIMESTAMP WITH TIME ZONE -- 软删除时间
);
-- 负责人必须是现有用户，避免审批配置指向不存在的账号。
ALTER TABLE ims_department ADD CONSTRAINT fk_department_leader FOREIGN KEY (leader_user_id) REFERENCES ims_user(id);

CREATE TABLE ims_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 角色稳定标识
    role_code VARCHAR(50) NOT NULL UNIQUE, -- 兼容客户端和审批规则的角色编码
    role_name VARCHAR(100) NOT NULL, -- 中文展示名称
    role_level INTEGER NOT NULL DEFAULT 5, -- 审批规则可读取的角色级别，不自动授予权限
    status INTEGER NOT NULL DEFAULT 1 CHECK (status IN (0, 1)), -- 停用角色不参与实时授权
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 创建时间
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP -- 最近修改时间
);

CREATE TABLE ims_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 权限标识
    perm_code VARCHAR(100) NOT NULL UNIQUE, -- 精确权限编码，只有星号为全局通配
    perm_name VARCHAR(100) NOT NULL, -- 中文权限名称
    module VARCHAR(50) NOT NULL, -- 所属业务模块
    description VARCHAR(500) NOT NULL DEFAULT '' -- 授权时向管理员展示的作用范围
);

CREATE TABLE ims_user_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 关联记录标识
    user_id BIGINT NOT NULL REFERENCES ims_user(id), -- 被授权账号
    role_id BIGINT NOT NULL REFERENCES ims_role(id), -- 授予角色
    CONSTRAINT uq_user_role UNIQUE (user_id, role_id) -- 同一账号不能重复分配角色
);

CREATE TABLE ims_role_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 关联记录标识
    role_id BIGINT NOT NULL REFERENCES ims_role(id), -- 受权角色
    permission_id BIGINT NOT NULL REFERENCES ims_permission(id), -- 授予的精确权限
    CONSTRAINT uq_role_permission UNIQUE (role_id, permission_id) -- 防止重复授予
);

CREATE TABLE ims_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 服务端会话记录标识
    user_id BIGINT NOT NULL REFERENCES ims_user(id), -- 凭证所属账号
    token_hash VARCHAR(64) NOT NULL UNIQUE, -- 随机令牌的SHA256摘要，数据库泄露不能直接复用凭证
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 签发时间
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL, -- 强制失效时间
    revoked_at TIMESTAMP WITH TIME ZONE -- 退出、停用或改密后的撤销时间
);
CREATE INDEX idx_user_department ON ims_user(dept_id); -- 部门内账号查询
CREATE INDEX idx_session_user ON ims_session(user_id); -- 批量撤销用户会话
CREATE INDEX idx_session_expiry ON ims_session(expires_at); -- 会话运维清理定位

