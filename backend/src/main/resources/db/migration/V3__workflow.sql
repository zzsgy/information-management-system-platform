CREATE TABLE approval_template (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, biz_type VARCHAR(30) NOT NULL CHECK (biz_type IN ('borrow','destroy')),
 description TEXT, priority INTEGER NOT NULL DEFAULT 0, enabled INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
 trigger_field VARCHAR(30), trigger_op VARCHAR(20), trigger_value VARCHAR(200),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE approval_template_node (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 template_id BIGINT NOT NULL REFERENCES approval_template(id) ON DELETE CASCADE,
 node_order INTEGER NOT NULL CHECK (node_order > 0), node_name VARCHAR(100) NOT NULL,
 approver_type VARCHAR(30) NOT NULL, approver_value VARCHAR(200), cond_field VARCHAR(30), cond_op VARCHAR(20), cond_value VARCHAR(200),
 is_countersign INTEGER NOT NULL DEFAULT 0 CHECK (is_countersign IN (0,1)), UNIQUE(template_id,node_order)
);
CREATE TABLE approval_flow (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 biz_type VARCHAR(30) NOT NULL CHECK (biz_type IN ('borrow','destroy')), biz_id BIGINT NOT NULL,
 title VARCHAR(200) NOT NULL, applicant_user_id BIGINT NOT NULL REFERENCES ims_user(id), template_id BIGINT,
 current_node INTEGER NOT NULL DEFAULT 0,
 status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 archive_summary TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(biz_type,biz_id)
);
CREATE TABLE approval_flow_archive (
 flow_id BIGINT NOT NULL REFERENCES approval_flow(id), archive_id BIGINT NOT NULL REFERENCES archive(id),
 PRIMARY KEY(flow_id,archive_id)
);
CREATE TABLE approval_flow_node (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, flow_id BIGINT NOT NULL REFERENCES approval_flow(id),
 node_order INTEGER NOT NULL, node_name VARCHAR(100) NOT NULL, approver_type VARCHAR(30) NOT NULL,
 approver_value VARCHAR(200), node_status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK(node_status IN ('pending','approved','rejected')),
 is_countersign INTEGER NOT NULL DEFAULT 0 CHECK(is_countersign IN (0,1)), UNIQUE(flow_id,node_order)
);
CREATE TABLE approval_node_assignee (
 node_id BIGINT NOT NULL REFERENCES approval_flow_node(id), user_id BIGINT NOT NULL REFERENCES ims_user(id),
 acted INTEGER NOT NULL DEFAULT 0 CHECK(acted IN (0,1)), PRIMARY KEY(node_id,user_id)
);
CREATE TABLE approval_flow_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, flow_id BIGINT NOT NULL REFERENCES approval_flow(id),
 node_id BIGINT NOT NULL REFERENCES approval_flow_node(id), action VARCHAR(20) NOT NULL CHECK(action IN ('agree','reject')),
 opinion TEXT, operator_user_id BIGINT NOT NULL REFERENCES ims_user(id), acted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(node_id,operator_user_id)
);
CREATE INDEX ix_approval_assignee_user ON approval_node_assignee(user_id,node_id);
CREATE INDEX ix_approval_flow_status ON approval_flow(status,biz_type);
CREATE TABLE borrow_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, borrow_no VARCHAR(50) NOT NULL UNIQUE,
 applicant_user_id BIGINT NOT NULL REFERENCES ims_user(id), applicant_dept_id BIGINT REFERENCES ims_department(id),
 apply_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, purpose VARCHAR(500), expected_return_date DATE, actual_return_date DATE,
 status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','borrowed','returned')),
 approved_by BIGINT REFERENCES ims_user(id), approved_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE borrow_detail (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, borrow_id BIGINT NOT NULL REFERENCES borrow_record(id),
 archive_id BIGINT NOT NULL REFERENCES archive(id), borrow_mode VARCHAR(20) NOT NULL CHECK(borrow_mode IN ('physical','electronic','both')),
 checkout_time TIMESTAMP, return_condition VARCHAR(500), UNIQUE(borrow_id,archive_id)
);
CREATE INDEX ix_borrow_detail_archive ON borrow_detail(archive_id);
CREATE TABLE destroy_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, applicant_user_id BIGINT NOT NULL REFERENCES ims_user(id),
 reason TEXT, scope_desc TEXT,
 status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','executed')),
 approved_by BIGINT REFERENCES ims_user(id), approved_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE destroy_request_detail (
 request_id BIGINT NOT NULL REFERENCES destroy_request(id), archive_id BIGINT NOT NULL REFERENCES archive(id),
 archive_no VARCHAR(100), archive_name VARCHAR(300), PRIMARY KEY(request_id,archive_id)
);
CREATE INDEX ix_destroy_request_archive ON destroy_request_detail(archive_id);
CREATE TABLE destroy_batch (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, destroy_request_id BIGINT NOT NULL UNIQUE REFERENCES destroy_request(id),
 batch_no VARCHAR(50) NOT NULL UNIQUE, executed_by BIGINT NOT NULL REFERENCES ims_user(id),
 executed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, witness VARCHAR(100), method VARCHAR(100)
);
CREATE TABLE destroy_detail (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id BIGINT NOT NULL REFERENCES destroy_batch(id),
 archive_id BIGINT NOT NULL REFERENCES archive(id), archive_no VARCHAR(100), archive_name VARCHAR(300),
 original_status VARCHAR(30), UNIQUE(batch_id,archive_id)
);
CREATE TABLE damage_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, archive_id BIGINT NOT NULL REFERENCES archive(id),
 reported_by BIGINT NOT NULL REFERENCES ims_user(id), reported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 damage_type VARCHAR(50), damage_desc TEXT, responsible_user_id BIGINT REFERENCES ims_user(id),
 handling_method VARCHAR(100), handling_result TEXT, handled_by BIGINT REFERENCES ims_user(id), handled_at TIMESTAMP,
 status VARCHAR(20) NOT NULL DEFAULT 'reported' CHECK(status IN ('reported','processing','resolved','closed')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE damage_handling_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, damage_id BIGINT NOT NULL REFERENCES damage_record(id),
 previous_status VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL,
 handling_method VARCHAR(100), handling_result TEXT, handled_by BIGINT NOT NULL REFERENCES ims_user(id),
 handled_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

